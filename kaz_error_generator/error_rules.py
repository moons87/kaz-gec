"""
Kazakh-specific error rules for synthetic error generation.

Цель: обучение модели грамматике и орфографии казахского языка.

Error categories:
  1. special_chars  — замена казахских букв на русские аналоги (орфография)
  2. typos          — опечатки: удвоение, перестановка, пропуск, вставка (орфография)
  3. punctuation    — ошибки в знаках препинания
  4. grammar        — морфологические ошибки: падежи, лицо/число, время, гармония гласных
"""

from dataclasses import dataclass, field
from typing import List


@dataclass
class ErrorRule:
    name: str
    category: str
    description: str


# ── 1. Казахские специальные буквы → русские аналоги ─────────────────────────
# Самая распространённая ошибка: люди без казахской клавиатуры пишут
# ближайшие русские буквы вместо казахских.

KAZ_SPECIAL_CHAR_MAP = {
    # Казахская → Русская (ошибочная)
    'ң': 'н',
    'ү': 'у',
    'і': 'и',
    'ғ': 'г',
    'қ': 'к',
    'ө': 'о',
    'ә': 'а',
    'ұ': 'у',
    # Заглавные
    'Ң': 'Н',
    'Ү': 'У',
    'І': 'И',
    'Ғ': 'Г',
    'Қ': 'К',
    'Ө': 'О',
    'Ә': 'А',
    'Ұ': 'У',
}

# Обратный маппинг для восстановления (используется в оценке)
REVERSE_SPECIAL_CHAR_MAP = {v: k for k, v in KAZ_SPECIAL_CHAR_MAP.items()
                             if v not in ('у', 'У')}  # 'у' — неоднозначно


# ── 2. Опечатки (typos) ──────────────────────────────────────────────────────
# Типичные опечатки при наборе текста на клавиатуре.
# Реализованы программно в generator.py:
#   - double:     кітап → кіттап   (удвоение буквы)
#   - transpose:  кітап → ктіап    (перестановка соседних букв)
#   - drop:       кітап → ктап     (пропуск буквы)
#   - insert:     кітап → кітааап  (вставка случайной буквы)

TYPO_TYPES = ['double', 'transpose', 'drop', 'insert']


